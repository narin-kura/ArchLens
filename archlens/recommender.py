"""Rule-based "Recommend My Stack" engine.

Given a short questionnaire (project type, scale, cloud preference, cost vs.
performance priority, database needs, AI needs, security level, and any
components the user already wants to use), picks a cost-optimized and secure
starter stack from the ArchLens service catalog (see web/static/index.html
SERVICES), grouped by architectural role.

If GEMINI_API_KEY or ANTHROPIC_API_KEY is configured, a short written
rationale is additionally generated by an LLM on top of the rule-based
picks (mirrors archlens.parsers.text.TextParser's provider fallback).
"""


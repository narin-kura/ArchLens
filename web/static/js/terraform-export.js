// Diagram -> Terraform: turns the canvas's nodes/edges into a starting .tf
// skeleton. Only services whose catalog `service` id is a real azurerm_/
// aws_/azuread_ resource type get a resource block — everything else (GCP,
// third-party tools, data stores) is listed as a TODO comment instead of a
// fabricated resource type. Diagram arrows become `depends_on` (an ordering
// hint only, not a real attribute reference) plus a plain-English summary,
// since guessing the correct linking attribute per resource-type pair would
// risk emitting Terraform that looks wired up but silently isn't.
// Copyright (c) 2026 K.N.Narin (github.com/narin-kura). All rights reserved.
// Non-commercial use only. See LICENSE.

const TF_PROVIDER_META = {
  'aws_':     {key: 'aws',     source: 'hashicorp/aws',     version: '~> 5.0'},
  'azurerm_': {key: 'azurerm', source: 'hashicorp/azurerm', version: '~> 3.90'},
  'azuread_': {key: 'azuread', source: 'hashicorp/azuread', version: '~> 2.47'},
};

function tfProviderFor(service) {
  if (!service) return null;
  for (const prefix of Object.keys(TF_PROVIDER_META)) {
    if (service.startsWith(prefix)) return TF_PROVIDER_META[prefix];
  }
  return null;
}

function tfSlug(name, fallback) {
  let s = (name || fallback || 'resource').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (!s) s = 'resource';
  if (/^[0-9]/.test(s)) s = 'r_' + s;
  return s;
}

function tfUniqueLabel(service, base, used) {
  let label = base, n = 1;
  while (used.has(service + '::' + label)) { n++; label = base + '_' + n; }
  used.add(service + '::' + label);
  return label;
}

function buildTerraformExport(diagramNodes, diagramEdges) {
  const used = new Set();
  const addrByUid = new Map();    // uid -> "service.label" address, real resources only
  const providersUsed = new Map();
  const unmapped = [];

  // Tiers run left-to-right the same way autoArrange lays the canvas out, so
  // the generated file reads top-to-bottom roughly how the diagram reads
  // left-to-right.
  const tierIndex = n => {
    const i = (typeof TIER_ORDER !== 'undefined') ? TIER_ORDER.indexOf(n.type) : -1;
    return i === -1 ? 999 : i;
  };
  const ordered = [...diagramNodes].sort((a, b) => tierIndex(a) - tierIndex(b));

  ordered.forEach(n => {
    const provider = tfProviderFor(n.service);
    if (!provider) { unmapped.push(n); return; }
    providersUsed.set(provider.key, provider);
    const label = tfUniqueLabel(n.service, tfSlug(n.name, n.service), used);
    addrByUid.set(n.uid, `${n.service}.${label}`);
  });

  const dependsByUid = new Map();
  diagramEdges.forEach(e => {
    if (!dependsByUid.has(e.to)) dependsByUid.set(e.to, []);
    dependsByUid.get(e.to).push(e.from);
  });

  const resourceBlocks = ordered
    .filter(n => addrByUid.has(n.uid))
    .map(n => {
      const address = addrByUid.get(n.uid);
      const label = address.slice(n.service.length + 1);
      const deps = (dependsByUid.get(n.uid) || [])
        .map(fromUid => addrByUid.get(fromUid))
        .filter(Boolean);
      const lines = [
        `resource "${n.service}" "${label}" {`,
        `  # TODO: configure this ${n.service} — drawn as "${n.name}" on the diagram.`,
      ];
      if (deps.length) lines.push(`  depends_on = [${deps.join(', ')}]`);
      lines.push('}');
      return lines.join('\n');
    });

  const out = [];
  out.push('# Generated by ArchLens from a diagram on ' + new Date().toISOString().slice(0, 10) + '.');
  out.push('#');
  out.push('# This is a starting skeleton, not deploy-ready Terraform:');
  out.push('#   - Resource bodies are left as TODOs; fill in the real arguments.');
  out.push('#   - depends_on reflects the diagram\'s arrows as an ORDERING hint only —');
  out.push('#     it does not wire up the actual attribute references (ids, ARNs,');
  out.push('#     connection strings, etc.). Add those by hand.');
  out.push('#   - Components with no confirmed Terraform resource type in ArchLens\'s');
  out.push('#     catalog are listed as TODOs below instead of a guessed resource type.');

  if (providersUsed.size) {
    out.push('');
    out.push('terraform {');
    out.push('  required_providers {');
    [...providersUsed.values()].forEach(p => {
      out.push(`    ${p.key} = {`);
      out.push(`      source  = "${p.source}"`);
      out.push(`      version = "${p.version}"`);
      out.push('    }');
    });
    out.push('  }');
    out.push('}');
  }

  if (resourceBlocks.length) {
    out.push('');
    out.push(resourceBlocks.join('\n\n'));
  }

  if (unmapped.length) {
    out.push('');
    out.push('# ---- Not yet mapped to a Terraform resource type ----');
    out.push('# ArchLens doesn\'t have a confirmed Terraform resource type for these yet,');
    out.push('# so no resource block was generated. Add them by hand:');
    unmapped.forEach(n => out.push(`#   - "${n.name}" (${n.provider})`));
  }

  if (diagramEdges.length) {
    out.push('');
    out.push('# ---- Diagram connections (for reference; see the depends_on note above) ----');
    diagramEdges.forEach(e => {
      const a = diagramNodes.find(n => n.uid === e.from);
      const b = diagramNodes.find(n => n.uid === e.to);
      if (!a || !b) return;
      const left = addrByUid.get(a.uid) || `"${a.name}"`;
      const right = addrByUid.get(b.uid) || `"${b.name}"`;
      out.push(`#   ${left} -> ${right}${e.label ? `   ["${e.label}"]` : ''}`);
    });
  }

  out.push('');
  return out.join('\n');
}

function exportDiagramAsTerraform() {
  if (!nodes.length) return;
  const hcl = buildTerraformExport(nodes, edges);
  const blob = new Blob([hcl], {type: 'text/plain'});
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = 'archlens-diagram.tf';
  a.click();
  URL.revokeObjectURL(url);
}

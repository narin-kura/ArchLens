"""Regenerate web/static/js/catalog_kubernetes.js from archlens/parsers/k8s_kinds.py.

Run from the repo root:  python scripts/gen_k8s_catalog.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from archlens.parsers.k8s_kinds import BUILTIN_KINDS, ECOSYSTEM_KINDS  # noqa: E402

entries = []
for kind, group, ctype, pgroup, name, icon, legacy in BUILTIN_KINDS:
    e = {"id": f"k8s_{kind.lower()}", "name": name, "type": ctype.name,
         "service": kind.lower(), "icon": icon, "group": pgroup,
         "apiVersion": f"{group}/" if group else "v1"}
    if legacy:
        e["legacy"] = True
    entries.append(e)
for kind, group, prefix, ctype, pgroup, name, icon in ECOSYSTEM_KINDS:
    entries.append({"id": f"k8s_{prefix}{kind.lower()}", "name": name, "type": ctype.name,
                    "service": prefix + kind.lower(), "icon": icon, "group": pgroup,
                    "apiVersion": f"{group}/"})

header = """// Copyright (c) 2026 K.N.Narin (github.com/narin-kura). All rights reserved.
// Non-commercial use only. Commercial use requires written permission: github.com/narin-kura
// See LICENSE for full terms.
//
// ArchLens — Kubernetes object catalog for the interactive builder.
// GENERATED by scripts/gen_k8s_catalog.py from archlens/parsers/k8s_kinds.py —
// edit that file and regenerate; do not edit this one by hand. `service` is
// exactly what the manifest parser emits for the kind, so a diagram node and a
// parsed manifest are analysed by the same checks.
"""
body = "window.K8S_CATALOG = " + json.dumps(
    [{"provider": "kubernetes", "cat": "kubernetes", **e} for e in entries], indent=1) + ";\n"
out = Path(__file__).resolve().parent.parent / "web/static/js/catalog_kubernetes.js"
out.write_text(header + body, encoding="utf-8")
print(f"wrote {len(entries)} entries to {out.name}")

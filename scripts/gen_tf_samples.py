"""Regenerate web/static/js/tf-samples.js from the bundled reference architectures.

Each resource type's sample body is the first block of that type found in
examples/architectures*/ — blocks that already pass ArchLens's own analysis,
and (for Oracle Cloud) were checked against the provider docs. The diagram's
Terraform export uses them to fill in resource bodies instead of leaving TODOs.

Types no reference architecture uses can get a hand-written sample in
scripts/tf_samples/<type>.tf.

Run from the repo root:  python scripts/gen_tf_samples.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = re.compile(r'resource\s+"([a-z0-9_]+)"\s+"([^"]+)"\s*\{')
# Lines that only make sense in the source file: a provider alias the export
# won't declare, explicit ordering against blocks that won't exist, and
# count/for_each scaffolding.
DROP_LINE = re.compile(r'^\s*(provider|depends_on|count|for_each)\s*=')
SKIP_BODY = re.compile(r'\bcount\.index\b|\beach\.(key|value)\b')


def blocks(text):
    for m in HEADER.finditer(text):
        depth, i = 1, m.end()
        while depth and i < len(text):
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        yield m.group(1), text[m.end():i - 1]


def clean(body):
    lines = [l for l in body.strip("\n").splitlines() if not DROP_LINE.match(l)]
    # Normalize to a 2-space indent regardless of the source block's nesting.
    indents = [len(l) - len(l.lstrip()) for l in lines if l.strip()]
    cut = min(indents) if indents else 0
    out = ["  " + l[cut:] if l.strip() else "" for l in lines]
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def listed(name):
    path = ROOT / "scripts" / name
    if not path.exists():
        return set()
    return {l.strip() for l in path.read_text(encoding="utf-8").splitlines()
            if l.strip() and not l.startswith("#")}


UNSUPPORTED = listed("tf_unsupported_types.txt")
# Samples whose source block fails `terraform validate` on the current
# provider major — fix the example, then remove it from this list.
FAILING = listed("tf_sample_failures.txt")

samples = {}
for d in sorted((ROOT / "examples").glob("architectures*/*/")):
    tf = d / "main.tf"
    if not tf.is_file():
        continue
    for rtype, body in blocks(tf.read_text(encoding="utf-8")):
        if rtype in samples or rtype in UNSUPPORTED or rtype in FAILING or SKIP_BODY.search(body):
            continue
        cleaned = clean(body)
        if cleaned:
            samples[rtype] = {"body": cleaned, "from": f"reference architecture {d.parent.name}/{d.name}"}

# Hand-written samples for types no reference architecture uses yet. A
# reference block, when there is one, wins.
for tf in sorted((ROOT / "scripts" / "tf_samples").glob("*.tf")):
    for rtype, body in blocks(tf.read_text(encoding="utf-8")):
        if rtype in samples or rtype in UNSUPPORTED or rtype in FAILING:
            continue
        samples[rtype] = {"body": clean(body), "from": "ArchLens sample library"}

header = """// Copyright (c) 2026 K.N.Narin (github.com/narin-kura). All rights reserved.
// Non-commercial use only. See LICENSE.
//
// Sample resource bodies for the diagram's Terraform export, keyed by resource
// type. GENERATED by scripts/gen_tf_samples.py from examples/architectures*/ —
// edit the examples and regenerate; do not edit this file by hand.
"""
out = ROOT / "web/static/js/tf-samples.js"
out.write_text(header
               + "window.TF_UNSUPPORTED_TYPES = " + json.dumps(sorted(UNSUPPORTED)) + ";\n"
               + "window.TF_SAMPLES = " + json.dumps(dict(sorted(samples.items())), indent=1) + ";\n",
               encoding="utf-8")
print(f"wrote {len(samples)} sample bodies to {out.name}")

"""Regenerate web/static/js/k8s-templates.js from scripts/k8s_templates/*.yaml.

Each template is one Kubernetes object with __NAME__ / __NAMESPACE__
placeholders and secure defaults. The diagram's "Export Kubernetes" button
copies them per node and wires them together; see scripts/k8s_templates/README.md.

Run from the repo root:  python scripts/gen_k8s_templates.py
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "k8s_templates"
OUT = ROOT / "web" / "static" / "js" / "k8s-templates.js"


def load(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    note_lines = []
    for line in text.splitlines():
        if line.startswith("# "):
            note_lines.append(line[2:].strip())
        else:
            break
    obj = yaml.safe_load(text)
    if not isinstance(obj, dict) or "kind" not in obj or "apiVersion" not in obj:
        raise SystemExit(f"{path.name}: not a single Kubernetes object")
    if path.stem != obj["kind"]:
        raise SystemExit(f"{path.name}: file name must match kind {obj['kind']}")
    return {"kind": obj["kind"], "note": " ".join(note_lines), "object": obj}


def main() -> None:
    templates = {}
    for path in sorted(SRC.glob("*.yaml")):
        t = load(path)
        # Keyed by the diagram catalog's service id: the kind in lowercase.
        templates[t["kind"].lower()] = t
    # Keep each template's own key order (apiVersion, kind, metadata, spec).
    body = json.dumps(templates, indent=1)
    OUT.write_text(
        "// GENERATED by scripts/gen_k8s_templates.py from scripts/k8s_templates/*.yaml.\n"
        "// Edit the YAML files and regenerate; do not edit this file by hand.\n"
        "// Copyright (c) 2026 K.N.Narin (github.com/narin-kura). All rights reserved.\n"
        "// Non-commercial use only. See LICENSE.\n"
        f"window.K8S_TEMPLATES = {body};\n",
        encoding="utf-8", newline="\n",
    )
    print(f"{len(templates)} templates -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

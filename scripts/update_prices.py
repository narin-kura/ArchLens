"""Rebuild archlens/data/prices.json from the cloud providers' official price lists.

    python scripts/update_prices.py                 # all providers
    python scripts/update_prices.py --only azure oci  # refresh some, keep the rest

Sources (see scripts/pricing/*.py): AWS Price List files, Azure Retail Prices
API, Google Cloud Billing Catalog API, Oracle Cloud price list API. Only GCP
needs a credential (GCP_PRICING_API_KEY or a signed-in gcloud CLI).

Downloads are cached in .price-cache/ (the AWS EC2 files are ~300 MB each);
delete that folder to force fresh downloads. Run the tests afterwards:
    python -m pytest tests -q
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from scripts.pricing import aws, azure, gcp, oci  # noqa: E402
from scripts.pricing.common import Rates  # noqa: E402

OUT = ROOT / "archlens" / "data" / "prices.json"
CACHE = ROOT / ".price-cache"

REGIONS = {
    "us": {"label": "United States", "aws": "us-east-1", "azure": "eastus", "gcp": "us-central1", "oci": "us-ashburn-1"},
    "in": {"label": "India (Mumbai / Pune)", "aws": "ap-south-1", "azure": "centralindia", "gcp": "asia-south1",
           "oci": "ap-mumbai-1"},
}
GCP_PLACE = {"us-central1": "Iowa", "asia-south1": "Mumbai"}
PRICING_PAGES = {
    "aws": "https://aws.amazon.com/pricing/",
    "azure": "https://azure.microsoft.com/pricing/",
    "gcp": "https://cloud.google.com/pricing/list",
    "oci": "https://www.oracle.com/cloud/price-list/",
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", nargs="+", choices=["aws", "azure", "gcp", "oci"])
    args = ap.parse_args()
    providers = args.only or ["aws", "azure", "gcp", "oci"]

    old = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    rates = Rates()
    sources: dict[str, dict] = dict(old.get("sources", {}))

    for provider in providers:
        published = ""
        for region_key, region in REGIONS.items():
            key = f"{provider}:{region_key}"
            print(f"fetching {key} ({region[provider]}) ...", flush=True)
            if provider == "aws":
                published = aws.fetch(region["aws"], CACHE, rates, key)
            elif provider == "azure":
                published = azure.fetch(region["azure"], rates, key)
            elif provider == "gcp":
                published = gcp.fetch(region["gcp"], GCP_PLACE[region["gcp"]], rates, key)
            else:
                published = oci.fetch(rates, key)
        module = {"aws": aws, "azure": azure, "gcp": gcp, "oci": oci}[provider]
        sources[provider] = {"name": module.SOURCE, "published": published, "pricing_page": PRICING_PAGES[provider]}

    data = {
        "_about": "Generated by scripts/update_prices.py from official provider price lists. Do not edit by hand. "
                  "USD, on-demand / pay-as-you-go list prices, before taxes, discounts and free tiers.",
        "generated": date.today().isoformat(),
        "hours_per_month": 730,
        "regions": REGIONS,
        "sources": sources,
        "rates": {**{k: v for k, v in old.get("rates", {}).items() if k.split(":")[0] not in providers},
                  **rates.rates},
        "tables": {**{k: v for k, v in old.get("tables", {}).items() if k.split(":")[0] not in providers},
                   **rates.tables},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    for key in sorted(data["rates"]):
        sizes = sum(len(t) for t in data["tables"].get(key, {}).values())
        print(f"  {key}: {len(data['rates'][key])} unit prices, {sizes} sized prices")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

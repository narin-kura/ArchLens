"""Regenerate web/static/js/catalog_onprem.js from archlens/parsers/onprem_resources.py.

Run from the repo root:  python scripts/gen_onprem_catalog.py
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from archlens.parsers.onprem_resources import PHYSICAL, RESOURCES  # noqa: E402


def icon(name: str) -> str:
    letters = "".join(w[0] for w in re.split(r"[\s()/-]+", name) if w and w[0].isalnum()).upper()
    return letters[:4] or "ONP"


entries = [{"id": f"onprem_{rtype}", "name": name, "type": ctype.name, "service": rtype,
            "icon": icon(name), "group": platform}
           for rtype, ctype, platform, name in RESOURCES]
entries += [{"id": f"onprem_{suffix}", "name": name, "type": ctype.name, "service": f"onprem_{suffix}",
             "icon": ic, "group": "Physical & Appliances"}
            for suffix, ctype, name, ic in PHYSICAL]

header = """// Copyright (c) 2026 K.N.Narin (github.com/narin-kura). All rights reserved.
// Non-commercial use only. Commercial use requires written permission: github.com/narin-kura
// See LICENSE for full terms.
//
// ArchLens — on-premises infrastructure catalog for the interactive builder:
// VMware vSphere, OpenStack, Nutanix and Proxmox VE (every resource type in
// each provider's docs tree), plus physical gear with no Terraform resource.
// GENERATED by scripts/gen_onprem_catalog.py from
// archlens/parsers/onprem_resources.py — edit that file and regenerate.
"""
body = "window.ONPREM_CATALOG = " + json.dumps(
    [{"provider": "onprem", "cat": "onprem", **e} for e in entries], indent=1) + ";\n"
out = Path(__file__).resolve().parent.parent / "web/static/js/catalog_onprem.js"
out.write_text(header + body, encoding="utf-8")
print(f"wrote {len(entries)} entries to {out.name}")
